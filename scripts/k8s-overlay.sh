#!/usr/bin/env bash
# Generate k8s/build/{app,index,eval}: the manifests in k8s/base and k8s/jobs/*, plus this deployment's
# image addresses and AWS settings, all read from Terraform's outputs. git-ignored, regenerated on
# every deploy, so nothing account-specific is committed.
#   ./scripts/k8s-overlay.sh
set -euo pipefail
cd "$(dirname "$0")/.."

TF="terraform -chdir=terraform"
REPOS=$($TF output -json ecr_repositories)
TAGS=$($TF output -json imported_image_tags)
get() { python3 -c 'import json,sys; print(json.loads(sys.argv[1])[sys.argv[2]])' "$1" "$2"; }
RAG_TAG=$(scripts/image-tag.sh rag)

for kind in app index eval; do
  base=$([[ $kind == app ]] && echo base || echo "jobs/$kind")
  mkdir -p "k8s/build/$kind"
  cat >"k8s/build/$kind/kustomization.yaml" <<YAML
# Generated by scripts/k8s-overlay.sh. Do not edit.
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
namespace: clinical-ai
resources:
  - ../../$base
images:
  - { name: rag, newName: $(get "$REPOS" rag), newTag: "$RAG_TAG" }
  - { name: vllm, newName: $(get "$REPOS" vllm), newTag: "$(get "$TAGS" vllm)" }
  - { name: tei, newName: $(get "$REPOS" tei), newTag: "$(get "$TAGS" tei)" }
  - { name: tei-gpu, newName: $(get "$REPOS" tei-gpu), newTag: "$(get "$TAGS" tei-gpu)" }
configMapGenerator:
  - name: aws-settings
    literals:
      - AWS_DEFAULT_REGION=$($TF output -raw region)
      - FHIR_URL=$($TF output -raw fhir_internal_url)
      - DATABASE_HOST=$($TF output -raw db_host)
      - DATABASE_SECRET_ARN=$($TF output -raw db_secret_arn)
      - MODELS_URI=$($TF output -raw models_uri)
YAML
done
echo "Generated k8s/build/{app,index,eval} (rag image tag $RAG_TAG)"
